# 実際の問い合わせに近い割合（問合せが多く、その他は少なめ）
WEIGHTS = {"問合せ": 40, "苦情": 25, "お礼": 15, "その他": 20}
HEADER = ("受信日時", "差出人", "アドレス", "件名", "本文", "種別")


def _values(rnd: random.Random) -> dict[str, object]:
    """1 通の中で使う商品・色・注文番号など（同じ通の中では同じものを使う）。"""
    return {
        "p": rnd.choice(PRODUCTS),
        "f": rnd.choice(FRAGILE),
        "k": rnd.choice(KITS),
        "c": rnd.choice(COLORS),
        "w": rnd.choice(WHEN),
        "n": rnd.randint(2, 5),
        "o": f"KM-{rnd.randint(2501, 2512):04d}{rnd.randint(1, 28):02d}-{rnd.randint(1, 9999):04d}",
    }


def _message(rnd: random.Random, kind: str) -> tuple[str, str]:
    """件名と本文。件名は最初の用件から決める。添える文は 0〜2 つ、あいさつを前後に付ける。"""
    v = _values(rnd)
    # 問い合わせは用件を 2 つ書くこともある。苦情などは 1 つ（2 つ並べると話が食い違うことがあるため）
    topics = rnd.sample(TOPICS[kind], k=rnd.choice((1, 1, 2)) if kind == "問合せ" else 1)
    extra = rnd.sample(EXTRA[kind], k=rnd.choice((0, 1, 1, 2))) if kind in EXTRA else []
    sentences = [rnd.choice(GREET), *(t[1] for t in topics), *extra, rnd.choice(CLOSE)]
    return topics[0][0].format(**v), "".join(x.format(**v) for x in sentences if x)


def rows(n: int, seed: int = 20260926) -> list[tuple[str, ...]]:
    rnd = random.Random(seed + n)
    start = datetime(2025, 7, 1, 9, 0, tzinfo=ZoneInfo("Asia/Tokyo"))
    kinds = list(WEIGHTS)
    seen: set[str] = set()
    out: list[tuple[str, ...]] = []
    at = start
    while len(out) < n:
        kind = rnd.choices(kinds, weights=[WEIGHTS[k] for k in kinds])[0]
        subject, body = _message(rnd, kind)
        if body in seen:
            continue
        seen.add(body)
        i = len(out) + 1
        at += timedelta(minutes=rnd.randint(3, 90))
        out.append(
            (
                at.strftime("%Y/%m/%d %H:%M"),
                f"お客様{i:04d}",
                f"customer{i:04d}@example.com",
                subject,
                body,
                kind,
            )
        )
    return out


def main() -> None:
    for n in SIZES:
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\r\n")
        w.writerow(HEADER)
        w.writerows(rows(n))
        path = OUT / f"大量_{n}件.csv"
        # Excel で開けるよう BOM 付きの UTF-8 にする
        path.write_bytes(buf.getvalue().encode("utf-8-sig"))
        print(f"{path.relative_to(OUT.parent.parent.parent)}: {n} 件")


if __name__ == "__main__":
    main()
